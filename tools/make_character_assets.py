"""Bake the supplied character clip into the app's transparent animation atlas.

Usage: python tools/make_character_assets.py path/to/character.mp4
Requires OpenCV, NumPy and Pillow (available in the AI trainer environment).
The generated PNG/header are checked in; building/running the app needs none
of these tools, the original clip, its audio, or a video decoder.
"""
import argparse
import hashlib
import json
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT = 216, 312
# Match the supplied clip's native cadence; keep the nine-second playback speed.
FPS, COLUMNS, PADDING = 24, 9, 2
OVERLAP = 1.0


def smoothstep(value):
    value = np.clip(value, 0, 1)
    return value * value * (3 - 2 * value)


def portrait(frame):
    """Retain the halo/upper figure, with no rectangular video background."""
    height, width = frame.shape[:2]
    crop_height = min(height, round(width * HEIGHT / WIDTH))
    rgb = cv2.cvtColor(frame[:crop_height], cv2.COLOR_BGR2RGB)
    rgb = np.asarray(Image.fromarray(rgb).resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS), dtype=np.float32)
    # Remove the nearly black matte without a hard luminance-key outline.
    alpha = np.clip((rgb.max(axis=2) - 3) / 29, 0, 1)
    straight = np.clip(rgb / np.maximum(alpha[..., None], 1 / 255), 0, 255)
    x = np.linspace(0, 1, WIDTH)[None, :]
    y = np.linspace(0, 1, HEIGHT)[:, None]
    feather = smoothstep(x / .10) * smoothstep((1 - x) / .10)
    feather = feather * smoothstep(y / .045) * smoothstep((1 - y) / .27)
    alpha *= feather
    rgba = np.dstack((straight, alpha * 255)).round().astype(np.uint8)
    rgba[rgba[..., 3] == 0] = 0
    return Image.fromarray(rgba)


def crossfade(first, second, weight):
    """Blend in premultiplied space, avoiding dark/bright transparent fringes."""
    a, b = (np.asarray(image, dtype=np.float32) / 255 for image in (first, second))
    alpha = a[..., 3:] * (1 - weight) + b[..., 3:] * weight
    color = a[..., :3] * a[..., 3:] * (1 - weight) + b[..., :3] * b[..., 3:] * weight
    color = color / np.maximum(alpha, 1 / 255)
    rgba = np.concatenate((color, alpha), axis=2).clip(0, 1)
    rgba = (rgba * 255).round().astype(np.uint8)
    rgba[rgba[..., 3] == 0] = 0
    return Image.fromarray(rgba)


def generate(source):
    capture = cv2.VideoCapture(str(source))
    try:
        source_fps = capture.get(cv2.CAP_PROP_FPS)
        source_count = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
        if not capture.isOpened() or source_fps <= 0 or source_count <= 0:
            raise ValueError("Cannot read the character clip")
        duration = source_count / source_fps
        count = int((duration - OVERLAP) * FPS)
        if count < FPS:
            raise ValueError("Character clip needs at least two seconds")
        period = count / FPS
        cell_w, cell_h = WIDTH + 2 * PADDING, HEIGHT + 2 * PADDING
        atlas = Image.new("RGBA", (COLUMNS * cell_w, ((count + COLUMNS - 1) // COLUMNS) * cell_h))

        def read(seconds):
            capture.set(cv2.CAP_PROP_POS_FRAMES, min(source_count - 1, round(seconds * source_fps)))
            ok, frame = capture.read()
            if not ok:
                raise ValueError(f"Cannot decode character frame at {seconds:.3f}s")
            return portrait(frame)

        for index in range(count):
            seconds = OVERLAP + index / FPS
            frame = read(seconds)
            if seconds >= period:
                into_join = seconds - period
                frame = crossfade(frame, read(into_join), float(smoothstep(into_join / OVERLAP)))
            atlas.paste(frame, ((index % COLUMNS) * cell_w + PADDING, (index // COLUMNS) * cell_h + PADDING))
    finally:
        capture.release()

    assets = ROOT / "packaging/assets"
    atlas_path = assets / "character-atlas.png"
    atlas.save(atlas_path, optimize=True)
    metadata = {
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "source_frames": source_count, "source_fps": source_fps,
        "width": WIDTH, "height": HEIGHT, "padding": PADDING,
        "columns": COLUMNS, "frames": count, "fps": FPS, "period_seconds": period,
        "loop_crossfade_seconds": OVERLAP,
        "atlas_sha256": hashlib.sha256(atlas_path.read_bytes()).hexdigest(),
    }
    (assets / "character-atlas.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    (ROOT / "include/BrandCharacterAtlas.h").write_text(
        "// Generated by tools/make_character_assets.py; do not edit separately.\n"
        "#pragma once\n\nnamespace CharacterAtlas {\n"
        f"constexpr int Width = {WIDTH}, Height = {HEIGHT}, Padding = {PADDING};\n"
        f"constexpr int Columns = {COLUMNS}, Frames = {count}, Fps = {FPS};\n"
        "constexpr int CellWidth = Width + 2 * Padding, CellHeight = Height + 2 * Padding;\n"
        "constexpr float Period = static_cast<float>(Frames) / Fps;\n"
        "} // namespace CharacterAtlas\n", encoding="utf-8")
    print(f"{atlas_path}: {count} frames, {period:g}s, {atlas_path.stat().st_size:,} bytes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    generate(parser.parse_args().source.resolve())
