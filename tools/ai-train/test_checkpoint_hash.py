"""Generated-file/GUI tests only: no model loading, training, GPU or real settings writes."""
import contextlib
import hashlib
import io
import json
import os
from pathlib import Path
import tempfile
import time
from types import SimpleNamespace
import unittest
from unittest.mock import Mock, patch

from mefi import checkpoint_hash


class FingerprintTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='checkpoint-hash-generated-')
        self.addCleanup(self.temp.cleanup)
        self.path = Path(self.temp.name) / 'generated checkpoint.pt'
        self.path.write_bytes(b'generated bytes only, not a loadable checkpoint')

    def test_exact_streamed_fingerprint_and_source_unchanged(self):
        data = b'generated fixture\x00\xff' * 140000
        self.path.write_bytes(data)
        before = checkpoint_hash.file_identity(self.path)
        result = checkpoint_hash.fingerprint(self.path)
        self.assertEqual(result['path'], str(self.path.resolve()))
        self.assertEqual(result['sha256'], hashlib.sha256(data).hexdigest())
        self.assertEqual(result['identity'], before)
        self.assertEqual(checkpoint_hash.file_identity(self.path), before)
        self.assertEqual(self.path.read_bytes(), data)

    def test_missing_file_and_directory_fail(self):
        with self.assertRaises(OSError):
            checkpoint_hash.fingerprint(self.path.with_name('missing.pt'))
        with self.assertRaisesRegex(ValueError, 'file'):
            checkpoint_hash.fingerprint(self.path.parent)

    def test_file_changed_while_reading_is_rejected(self):
        digest = hashlib.sha256()
        changed = False
        class ChangingDigest:
            def update(_self, block):
                nonlocal changed
                digest.update(block)
                if not changed:
                    changed = True
                    with self.path.open('ab') as handle:
                        handle.write(b'changed during read')
            def hexdigest(_self):
                return digest.hexdigest()
        with patch.object(checkpoint_hash.hashlib, 'sha256', return_value=ChangingDigest()):
            with self.assertRaisesRegex(ValueError, 'changed during'):
                checkpoint_hash.fingerprint(self.path)

    def test_path_replacement_after_read_is_rejected(self):
        different = checkpoint_hash.file_identity(self.path)
        different[1] += 1
        with patch.object(checkpoint_hash, 'file_identity', return_value=different):
            with self.assertRaisesRegex(ValueError, 'changed during'):
                checkpoint_hash.fingerprint(self.path)

    def test_worker_emits_request_and_lowercase_digest(self):
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            code = checkpoint_hash.main(['--path', str(self.path), '--request', 'generated-request'])
        event = json.loads(output.getvalue())
        self.assertEqual(code, 0)
        self.assertEqual(event['event'], 'checkpoint_hash')
        self.assertEqual(event['request'], 'generated-request')
        self.assertEqual(event['sha256'], hashlib.sha256(self.path.read_bytes()).hexdigest())

    def test_worker_reports_permission_error_without_loading(self):
        output = io.StringIO()
        with patch('builtins.open', side_effect=PermissionError('generated denial')), contextlib.redirect_stdout(output):
            code = checkpoint_hash.main(['--path', str(self.path), '--request', 'failed-request'])
        event = json.loads(output.getvalue())
        self.assertEqual(code, 1)
        self.assertEqual(event['event'], 'checkpoint_hash_error')
        self.assertEqual(event['request'], 'failed-request')
        self.assertIn('generated denial', event['message'])


class InterfaceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')
        import app
        from PySide6.QtTest import QTest
        cls.ui, cls.qtest = app, QTest
        cls.application = app.QApplication.instance() or app.QApplication([])

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='checkpoint-hash-interface-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.path = self.root / 'generated weights.pt'
        self.path.write_bytes(b'GUI fingerprint fixture; must never be deserialized')
        self.page = None

    def tearDown(self):
        if self.page:
            self.page.cancel_initial_hash()
            if self.page.hash_job.running():
                self.page.hash_job.proc.waitForFinished(2000)
            self.page.deleteLater()
            self.application.processEvents()

    def make_page(self, settings=None):
        self.owner = SimpleNamespace(settings=settings or {}, store=Mock(), set_busy=Mock())
        self.page = self.ui.TrainPage(self.owner)
        self.page.job.start = Mock(side_effect=AssertionError('Training is forbidden in this suite'))
        self.page.run.setText(str(self.root / 'unused-run'))
        labels = self.root / 'generated-labels.json'
        labels.write_text('{}', encoding='utf-8')  # GUI file selection only; no training/decoding.
        self.page.ui_labels.setText(str(labels))
        self.page.ui_mode.setCurrentIndex(self.page.ui_mode.findData('frozen'))
        return self.page

    def wait_hash(self):
        deadline = time.monotonic() + 8
        while time.monotonic() < deadline:
            self.qtest.qWait(10)
            if self.page._initial_hash_valid or self.page._initial_hash_error:
                return
        self.fail('Checkpoint hash worker did not finish')

    def test_typed_path_automatically_hashes_in_separate_process(self):
        page = self.make_page()
        page.init_from.setText(str(self.path))
        self.assertEqual(page.ui_init_sha.text(), '')
        self.wait_hash()
        self.assertFalse(page._initial_hash_error)
        self.assertEqual(page.ui_init_sha.text(), hashlib.sha256(self.path.read_bytes()).hexdigest())
        self.assertTrue(page.ui_init_sha.isReadOnly())
        self.assertTrue(page.initial_hash_ready(str(self.path)))
        page.job.start.assert_not_called()
        self.owner.store.assert_not_called()

    def test_browse_hashes_without_manual_digest_and_passes_pin(self):
        page = self.make_page()
        with patch.object(self.ui.QFileDialog, 'getOpenFileName', return_value=(str(self.path), '')):
            page.pick_initial()
        self.wait_hash()
        with patch.object(page.job, 'start') as start:
            page.start()
        module, args = start.call_args.args
        self.assertEqual(module, 'mefi.train_ui')
        self.assertEqual(args[args.index('--init-from') + 1], str(self.path))
        self.assertEqual(args[args.index('--init-sha256') + 1], hashlib.sha256(self.path.read_bytes()).hexdigest())

    def test_start_waits_for_hash_and_does_not_autostart_training(self):
        page = self.make_page()
        page.init_from.setText(str(self.path))
        page.start()
        page.job.start.assert_not_called()
        self.assertIn('SHA256', page.status.text())
        self.wait_hash()
        page.job.start.assert_not_called()

    def test_flow_only_settings_keep_the_fingerprint_with_its_selected_path(self):
        page = self.make_page()
        page.ui_mode.setCurrentIndex(page.ui_mode.findData('off'))
        data = self.root / 'generated-flow'
        data.mkdir()
        (data / 'index.json').write_text('[]', encoding='utf-8')
        page.add_dataset(str(data))
        page.init_from.setText(str(self.path))
        self.wait_hash()
        with patch.object(page.job, 'start') as start:
            page.start()
        self.assertEqual(start.call_args.args[0], 'mefi.train')
        stored = self.owner.store.call_args.args[0]
        self.assertEqual(stored['init_from'], str(self.path))
        self.assertEqual(stored['ui_init_sha'], hashlib.sha256(self.path.read_bytes()).hexdigest())

    def test_clearing_initial_weights_clears_hash_for_scratch(self):
        page = self.make_page()
        page.init_from.setText(str(self.path))
        self.wait_hash()
        page.init_from.clear()
        self.assertEqual(page.ui_init_sha.text(), '')
        self.assertIsNone(page._initial_hash_valid)
        self.assertIn('scratch', page.hash_status.text())
        self.assertFalse(page.recalculate_sha.isEnabled())

    def test_stale_result_from_previous_selection_is_ignored(self):
        page = self.make_page()
        page.init_from.setText(str(self.path))
        old_request = page._initial_hash_request
        other = self.root / 'other.pt'
        other.write_bytes(b'different generated checkpoint')
        page.init_from.setText(str(other))
        page.on_initial_hash({'event': 'checkpoint_hash', 'request': old_request, **checkpoint_hash.fingerprint(self.path)})
        self.assertEqual(page.ui_init_sha.text(), '')
        self.wait_hash()
        self.assertEqual(page.ui_init_sha.text(), hashlib.sha256(other.read_bytes()).hexdigest())

    def test_saved_pin_is_verified_and_not_silently_replaced(self):
        page = self.make_page({'init_from': str(self.path), 'ui_init_sha': '0' * 64})
        self.wait_hash()
        self.assertIn('does not match', page._initial_hash_error)
        self.assertEqual(page.ui_init_sha.text(), '0' * 64)
        page.start()
        page.job.start.assert_not_called()
        page.recalculate_sha.click()  # Explicitly accept the selected file's current bytes.
        self.wait_hash()
        self.assertEqual(page.ui_init_sha.text(), hashlib.sha256(self.path.read_bytes()).hexdigest())
        self.assertFalse(page._initial_hash_error)

    def test_changed_file_blocks_start_and_retains_previous_pin(self):
        page = self.make_page()
        page.init_from.setText(str(self.path))
        self.wait_hash()
        original_pin = page.ui_init_sha.text()
        self.path.write_bytes(b'changed generated weights')
        page.start()
        page.job.start.assert_not_called()
        self.wait_hash()
        self.assertIn('does not match', page._initial_hash_error)
        self.assertEqual(page.ui_init_sha.text(), original_pin)

    def test_missing_file_reports_problem_without_job(self):
        page = self.make_page()
        with patch.object(page.hash_job, 'start') as start:
            page.init_from.setText(str(self.root / 'missing.pt'))
            self.qtest.qWait(250)
            start.assert_not_called()
        self.assertIn('existing', page.hash_status.text())
        page.start()
        page.job.start.assert_not_called()

    def test_continue_does_not_need_original_file_or_hash(self):
        page = self.make_page()
        page.resume.setChecked(True)
        with patch.object(page.hash_job, 'start') as hash_start, patch.object(page.job, 'start') as start:
            page.restore_initial_checkpoint(str(self.root / 'missing-original.pt'), 'a' * 64)
            page.start()
            self.qtest.qWait(250)
        hash_start.assert_not_called()
        self.assertEqual(start.call_args.args[0], 'mefi.train_ui')
        self.assertIn('--resume', start.call_args.args[1])
        self.assertNotIn('--init-from', start.call_args.args[1])
        self.assertEqual(page.ui_init_sha.text(), 'a' * 64)

    def test_cancelling_discards_pending_work_and_late_results(self):
        page = self.make_page()
        page.init_from.setText(str(self.path))
        request = page._initial_hash_request
        page.cancel_initial_hash()
        with patch.object(page.hash_job, 'start') as start:
            self.qtest.qWait(250)
        start.assert_not_called()
        page.on_initial_hash({'event': 'checkpoint_hash', 'request': request, **checkpoint_hash.fingerprint(self.path)})
        self.assertEqual(page.ui_init_sha.text(), '')
        self.assertIsNone(page._initial_hash_valid)


if __name__ == '__main__':
    unittest.main()
